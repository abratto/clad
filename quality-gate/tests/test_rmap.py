class RmapBehaviourTests(unittest.TestCase):

    def derive(self, concept, body):
        return rmap.derive_model(
            concept, "## Machine model\n\n```\n" + body + "\n```\n")

    def test_simple_table_and_reference_scheme(self):
        model = self.derive("UserNaming", """
object-type User identified-by UserId
fact username : User -> Username -- mandatory, unique
""")
        table = model.tables[0]
        self.assertEqual(table.table, "user_naming")
        self.assertEqual(table.id_column, "user_id")
        self.assertTrue(table.column_for("username").unique)
        self.assertTrue(table.column_for("username").mandatory)

    def test_multiple_object_types_make_a_table_set(self):
        model = self.derive("PartnerMatching", """
object-type Coverage identified-by CoverageId
object-type Partner identified-by PartnerId
fact domain : Coverage -> Domain -- mandatory
fact capacity : Coverage -> Int -- mandatory, default 0
fact firmCapacity : Partner -> Int -- mandatory, default 0
""")
        self.assertEqual(len(model.tables), 2)
        self.assertIsNotNone(model.table_for("Coverage"))
        self.assertIsNotNone(model.table_for("Partner"))

    def test_compound_subject_gets_compidot_table(self):
        model = self.derive("LegalOntology", """
object-type Firm identified-by FirmUri
object-type Service identified-by Service
fact provides : Firm -> { Service } -- zero or more
fact jurisdiction : ( Firm, Service ) -> Jurisdiction -- optional
""")
        compidot = next(t for t in model.tables if len(t.primary_key) == 2)
        self.assertEqual(compidot.primary_key, ["firm_uri", "service"])

    def test_multi_valued_fact_gets_child_table(self):
        model = self.derive("Ontology", """
object-type Firm identified-by FirmUri
fact provides : FirmUri -> { Service } -- zero or more
""")
        child = next(t for t in model.tables if len(t.primary_key) == 2)
        self.assertEqual(child.primary_key, ["firm_uri", "provides"])

    def test_value_constraint_becomes_check(self):
        model = self.derive("Analytics", """
object-type Fact identified-by FactId
fact eventType : FactId -> EventType -- mandatory, in {interaction, extraction}
""")
        self.assertIn("CHECK (event_type IN ('interaction', 'extraction'))",
                      rmap.render_migration("x", [model]))

    def test_filtered_uniqueness_becomes_partial_index(self):
        model = self.derive("Lending", """
object-type Loan identified-by Loan
fact loanCopy : Loan -> Copy -- mandatory, unique while returnedAt absent
fact returnedAt : Loan -> Timestamp -- optional
""")
        sql = rmap.render_migration("x", [model])
        self.assertIn("CREATE UNIQUE INDEX", sql)
        self.assertIn('"returned_at" IS NULL', sql)

    def test_separate_subtype_inherits_root_scheme(self):
        model = self.derive("PatientRegistry", """
object-type Person identified-by Person
object-type Patient identified-by Patient
fact name : Person -> Name -- mandatory
fact insurer : Patient -> Insurer -- optional
Patient is a Person -- mapping: separate
""")
        patient = model.table_for("Person")
        self.assertIsNotNone(patient)
        self.assertIn("patient_registry__patient", [t.table for t in model.tables])
        sql = rmap.render_migration("x", [model])
        self.assertIn('FOREIGN KEY ("person") REFERENCES '
                      '"patient_registry__person" ("person")', sql)

    def test_absorb_moves_subtype_facts_to_parent(self):
        model = self.derive("Staff", """
object-type Person identified-by Person
object-type Manager identified-by Manager
fact name : Person -> Name -- mandatory
fact reports : Manager -> Int -- optional
Manager is a Person -- mapping: absorb
""")
        self.assertEqual(len(model.tables), 1)
        self.assertIsNotNone(model.tables[0].column_for("reports"))

    def test_partition_flattens_supertype_facts(self):
        model = self.derive("Party", """
object-type Party identified-by Party
object-type Individual identified-by Individual
object-type Company identified-by Company
fact name : Party -> Name -- mandatory
Individual is a Party -- mapping: partition
Company is a Party -- mapping: partition
""")
        self.assertEqual(sorted(t.table for t in model.tables),
                         ["party__company", "party__individual"])
        for table in model.tables:
            self.assertIsNotNone(table.column_for("name"))

    def test_independent_type_is_a_single_column_table(self):
        model = self.derive("Scheduling", """
object-type Appointment identified-by Appointment
fact at : Appointment -> Timestamp -- mandatory
independent ReferralSource
""")
        independent = next(t for t in model.tables
                           if t.object_type == "ReferralSource")
        self.assertEqual(independent.primary_key, ["referral_source"])

    def test_identity_scheme_uses_entity_id(self):
        model = self.derive("Drink", """
object-type DrinkEntry identified-by DrinkEntry.id
fact amount : DrinkEntry -> Int -- mandatory
""")
        self.assertEqual(model.tables[0].id_column, "drink_entry_id")

    def test_descriptor_contains_predicate_column_mapping(self):
        model = self.derive("PasswordAuth", """
object-type UserId identified-by UserId
fact passwordHash : UserId -> PasswordHash -- mandatory
""")
        descriptor = rmap.model_descriptor([model])
        column = next(
            c for c in descriptor["models"][0]["tables"][0]["columns"]
            if c["predicate"] == "passwordHash")
        self.assertEqual(column["column"], "password_hash")


