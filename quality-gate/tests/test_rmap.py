def _models_for(paths):
    models = []
    for path in paths:
        concept = Path(path).name[:-len(".data-model.md")]
        models.append(rmap.derive_model(concept, Path(path).read_text(),
                                        str(path)))
    return models


def _write_corpus(features, names):
    corpus = Path(features) / "_system" / "concepts"
    corpus.mkdir(parents=True)
    for name in names:
        (corpus / f"{name}.data-model.md").write_text(
            "## Conceptual model\n\n```\n"
            f"object-type {name}Id identified-by {name}Id\n"
            f"fact label: {name}Id -> String -- mandatory\n"
            "```\n", encoding="utf-8")
    return Path(features)


def _normalise_generator(text):
    return "\n".join(
        "-- GENERATED by quality-gate/rmap.py from the Stage 03b"
        if line.startswith("-- GENERATED by ") else line
        for line in text.split("\n"))


class DomainParityTests(unittest.TestCase):

    def test_domain_fixtures_are_byte_identical(self):
        root = (REPO_ROOT / "reference-impl/legible-storage/src/test/"
                "resources/domains")
        for data_model in sorted(glob.glob(str(root / "*/*.data-model.md"))):
            expected = data_model.replace(".data-model.md", ".migration.sql")
            if not Path(expected).is_file():
                # Custom runtime-probe fixtures have a descriptor but no
                # migration oracle; the domain fixture set is the SQL oracle.
                continue
            first = Path(expected).read_text().splitlines()[0]
            label = first[len("-- Base DDL for "):-len(" concept state.")]
            got = rmap.render_migration(label, _models_for([data_model]))
            want = _normalise_generator(Path(expected).read_text())
            self.assertEqual(got, want, data_model)


