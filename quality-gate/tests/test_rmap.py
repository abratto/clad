class ProjectRmapTests(unittest.TestCase):

    def test_project_aggregate_reads_the_canonical_corpus(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            features = _write_corpus(root / "features", ["Alpha", "Beta"])
            out = root / "app-schema.json"
            self.assertEqual(rmap.main([
                "--features-dir", str(features),
                "--app-label", "app", "--json", str(out)]), 0)
            descriptor = json.loads(out.read_text())
        concepts = {model["concept"] for model in descriptor["models"]}
        self.assertEqual(concepts, {"Alpha", "Beta"})
        tables = {table["table"] for model in descriptor["models"]
                  for table in model["tables"]}
        self.assertEqual(tables, {"alpha", "beta"})

    def test_alter_creates_a_new_table(self):
        with tempfile.TemporaryDirectory() as temporary:
            features = _write_corpus(Path(temporary) / "features",
                                     ["Alpha", "Beta"])
            alpha = features / "_system" / "concepts" / "Alpha.data-model.md"
            beta = features / "_system" / "concepts" / "Beta.data-model.md"
            baseline = rmap.model_descriptor(_models_for([alpha]))
            current = rmap.model_descriptor(_models_for([alpha, beta]))
            sql, warnings = rmap._alter_sql(baseline, current, "app")
        self.assertIn('CREATE TABLE IF NOT EXISTS "beta"', sql)
        self.assertEqual(warnings, [])

    def test_alter_adds_a_nullable_column(self):
        def table(columns):
            return {"models": [{"concept": "X", "tables": [{
                "table": "x", "columns": columns, "primaryKey": ["id"],
                "checks": [], "ddl": "CREATE TABLE x (...)"}]}]}
        base = table([{"column": "id", "sqlType": "TEXT", "mandatory": True,
                       "unique": False, "default": None,
                       "valueConstraint": None}])
        current = table([
            {"column": "id", "sqlType": "TEXT", "mandatory": True,
             "unique": False, "default": None, "valueConstraint": None},
            {"column": "note", "sqlType": "TEXT", "mandatory": False,
             "unique": False, "default": None, "valueConstraint": None},
        ])
        sql, _warnings = rmap._alter_sql(base, current, "x")
        self.assertIn('ALTER TABLE "x" ADD COLUMN "note" varchar;', sql)

    def test_alter_refuses_a_mandatory_column_without_default(self):
        base = {"models": [{"concept": "X", "tables": [{
            "table": "x", "columns": [], "primaryKey": [], "checks": [],
            "ddl": "CREATE TABLE x (...)"}]}]}
        current = {"models": [{"concept": "X", "tables": [{
            "table": "x", "columns": [{
                "column": "note", "sqlType": "TEXT", "mandatory": True,
                "unique": False, "default": None, "valueConstraint": None}],
            "primaryKey": [], "checks": [], "ddl": "CREATE TABLE x (...)"}]}]}
        with self.assertRaises(SystemExit):
            rmap._alter_sql(base, current, "x")

    def test_default_baseline_is_discovered_automatically(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            features = _write_corpus(root / "features", ["Alpha"])
            self.assertEqual(rmap.main([
                "--features-dir", str(features),
                "--record-baseline", "default"]), 0)
            self.assertTrue((root / "_generated/rmap-baselines/default.json").is_file())
            alter = root / "alter.sql"
            self.assertEqual(rmap.main([
                "--features-dir", str(features),
                "--alter", str(alter)]), 0)
            self.assertIn("no schema changes", alter.read_text())

    def test_configured_baseline_is_discovered(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            features = _write_corpus(root / "features", ["Alpha"])
            (root / "clad.properties").write_text(
                "rmap.baseline=baselines/prod.json\n", encoding="utf-8")
            self.assertEqual(rmap.main([
                "--features-dir", str(features),
                "--record-baseline", "baselines/prod.json"]), 0)
            alter = root / "alter.sql"
            self.assertEqual(rmap.main([
                "--features-dir", str(features),
                "--alter", str(alter)]), 0)
            self.assertIn("no schema changes", alter.read_text())

    def test_write_guard_requires_force_for_a_changed_migration(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "V1.sql"
            path.write_text("old\n", encoding="utf-8")
            self.assertEqual(rmap._guarded_write(str(path), "new\n", False), 1)
            self.assertEqual(path.read_text(), "old\n")
            self.assertEqual(rmap._guarded_write(str(path), "new\n", True), 0)
            self.assertEqual(path.read_text(), "new\n")
            self.assertEqual(rmap._guarded_write(str(path), "new\n", False), 0)


