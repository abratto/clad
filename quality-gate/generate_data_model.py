def main() -> None:
    parser = argparse.ArgumentParser(
        description="Deterministically generate Stage 03b conceptual data models")
    parser.add_argument("--feature", required=True, help="Feature root path")
    parser.add_argument("--write", action="store_true",
                        help="Write files (default dry-run)")
    args = parser.parse_args()

    feature_root = os.path.abspath(args.feature)
    concept_dir = cs.CONCEPT_DIR(feature_root)
    data_dir = cs.DATA_DIR(feature_root)

    if not os.path.isdir(concept_dir):
        print("No concept directory found.")
        sys.exit(1)

    n = 0
    for fname in sorted(os.listdir(concept_dir)):
        if not fname.endswith(".concept.md"):
            continue
        concept = ap.parse_concept(os.path.join(concept_dir, fname))
        if concept.name == "Web":  # bootstrap — no data model
            continue
        out_path = os.path.join(data_dir, concept.name + ".data-model.md")
        content = render(concept)
        if args.write:
            os.makedirs(data_dir, exist_ok=True)
            with open(out_path, "w") as fh:
                fh.write(content + "\n")
            print(f"WROTE {cs.relpath(out_path, feature_root)}")
        else:
            rels = len(ap.parse_state_relations(concept.state_lines))
            print(f"WOULD WRITE {concept.name}.data-model.md  ({rels} relations)")
        n += 1

    if not args.write:
        print(f"\n{n} data models (dry run). Re-run with --write to emit files.")


if __name__ == "__main__":
    main()
